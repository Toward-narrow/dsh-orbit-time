#!/usr/bin/env node
/**
 * Build `lib/client.js` from src/client/*.js.
 *
 * The DSH browser module system consumes one lazy-CJS artifact per package:
 *
 *   window.__ModuleLoader__.load({ id: '<package name>', factory: (require) => ({...}) })
 *
 * The factory body runs in the page, may `require` only platform seed words and
 * other registered bundles, and returns the plugin exports (`inject` + `apply`).
 * We therefore wrap our authoring modules in a tiny in-factory registry so the
 * source can stay split across readable files with no bundler in the loop.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')
const srcDir = join(root, 'src', 'client')
const outFile = join(root, 'lib', 'client.js')

/** Load order matters only for readability: the registry is lazy. */
const MODULES = [
  'util.js',
  'ui.js',
  'drag.js',
  'store.js',
  'calendar.js',
  'manual.js',
  'pomodoro.js',
  'timeline.js',
  'companion.js',
  'import-view.js',
  'settings.js',
  'panel.js',
  'index.js',
]

/**
 * Modules that live outside `src/client/` because the host half imports them
 * too. They are authoring modules like any other — the client just needs its own
 * copy inlined, and `src/shared/*.cjs` keeps the host's ESM import working.
 */
const SHARED = [{ id: 'shared/repair.cjs', from: '../shared/repair.cjs' }]

const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const pkgName = pkg.name

const parts = []
const missing = []

/** Emit one authoring module as a registry entry. */
function emitModule(rel, body) {
  parts.push(
    `\t\t__otDefine(${JSON.stringify(rel)}, (module, exports, require) => {\n` +
      body.replace(/^/gm, '\t\t') +
      `\n\t\t});`,
  )
}

for (const file of MODULES) {
  const full = join(srcDir, file)
  if (!existsSync(full)) {
    missing.push(file)
    continue
  }
  emitModule('./' + file, readFileSync(full, 'utf8').replace(/\r\n/g, '\n'))
}

for (const shared of SHARED) {
  const full = resolve(srcDir, shared.from)
  if (!existsSync(full)) {
    missing.push(shared.from)
    continue
  }
  emitModule('./' + shared.id, readFileSync(full, 'utf8').replace(/\r\n/g, '\n'))
}

if (missing.length > 0) {
  console.error('build: missing client sources: ' + missing.join(', '))
  process.exit(1)
}

const cssPath = join(srcDir, 'styles.css')
const css = existsSync(cssPath) ? readFileSync(cssPath, 'utf8').replace(/\r\n/g, '\n') : ''

const banner = `/* ${pkgName} — generated by scripts/build-client.mjs. Do not edit lib/client.js directly. */\n`

const moduleNames = MODULES.map((file) => './' + file).concat(SHARED.map((shared) => './' + shared.id))

const out = `${banner}window.__ModuleLoader__.load({
\tid: ${JSON.stringify(pkgName)},
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });

\t\t// --- authoring module registry (source lives in src/client/*.js) ---
\t\t// Two rules keep this honest:
\t\t//   1. React is a bundle-level closure, never an inner module request —
\t\t//      the same shape the dynamic client half receives.
\t\t//   2. The inner resolver is __otRequire and is reached from authoring
\t\t//      modules through their factory-injected require parameter, so their
\t\t//      exports land on their own module object and not on this facade.
\t\tvar __otReact = require("react");
\t\tvar __otFactories = new Map();
\t\tvar __otCache = new Map();
\t\tfunction __otDefine(id, factory) { __otFactories.set(id, factory); }
\t\tfunction __otRequire(id) {
\t\t\tif (__otCache.has(id)) return __otCache.get(id).exports;
\t\t\tvar factory = __otFactories.get(id);
\t\t\tif (factory === void 0) throw new Error("orbit-time client: unknown module " + id);
\t\t\tvar mod = { exports: {} };
\t\t\t__otCache.set(id, mod);
\t\t\tfactory(mod, mod.exports, __otRequire);
\t\t\treturn mod.exports;
\t\t}

\t\tvar CSS = ${JSON.stringify(css)};
\t\tvar __otStyleDisposer = null;
\t\tfunction __otEnsureStyles() {
\t\t\tif (__otStyleDisposer !== null) return;
\t\t\tvar tagId = ${JSON.stringify(pkgName + '/styles.css')};
\t\t\tvar existing = document.querySelector('style[data-plugin-css=' + JSON.stringify(tagId) + ']');
\t\t\tif (existing !== null) return;
\t\t\tvar tag = document.createElement('style');
\t\t\ttag.dataset.plugin = ${JSON.stringify(pkgName)};
\t\t\ttag.dataset.pluginCss = tagId;
\t\t\ttag.textContent = CSS;
\t\t\tdocument.head.appendChild(tag);
\t\t\t__otStyleDisposer = function () { tag.remove(); __otStyleDisposer = null; };
\t\t}

${parts.join('\n\n')}

\t\t// Re-materialize the whole authoring graph on every load. The page module
\t\t// system skips a bundle it has already registered, so a client-plugin
\t\t// rebuild or reload re-runs this factory: a stale facade must never carry
\t\t// stale component identities into the slot registrations.
\t\tfunction __otActivate() {
\t\t\treturn __otRequire("./index.js");
\t\t}

\t\tvar __otApply = function (ctx) {
\t\t\tvar entry = __otActivate();
\t\t\t__otEnsureStyles();
\t\t\tif (ctx && typeof ctx.effect === "function") {
\t\t\t\tctx.effect(function () { return function () { if (__otStyleDisposer !== null) __otStyleDisposer(); }; }, "orbit-time: styles");
\t\t\t}
\t\t\treturn entry.apply(ctx);
\t\t};

\t\tvar __otPlugin = __otActivate();

\t\t// Public surface: apply/inject are the plugin contract; the per-module
\t\t// namespaces are live reads of the current graph rather than frozen
\t\t// snapshots, so a re-materialized bundle never serves a stale component.
\t\texports.apply = __otApply;
\t\texports.inject = __otPlugin.inject;
${moduleNames.map((name) => `\t\texports[${JSON.stringify(name)}] = __otRequire(${JSON.stringify(name)});`).join('\n')}

\t\treturn module.exports;
\t}
});
`

mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, out, 'utf8')
const kb = (Buffer.byteLength(out, 'utf8') / 1024).toFixed(1)
console.log(`build: wrote ${outFile} (${kb} kB) from ${parts.length} modules + ${(Buffer.byteLength(css, 'utf8') / 1024).toFixed(1)} kB css`)
