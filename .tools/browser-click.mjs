/**
 * Click through the panel in a real browser.
 *
 * A string render cannot answer "what happens after a click": hooks, effects, and
 * the second render never run, and a throw inside a handler or a re-render never
 * surfaces. This builds the client bundle into a page with the real React, mounts
 * the *registered* panel (the wrapped one the app mounts, not the raw export),
 * clicks the buttons a person would click, and prints what happened.
 *
 * It depends on nothing beyond the plugin's own dev dependencies, which is why it
 * is a browser rather than jsdom: Edge/Chrome is already on every Windows box.
 *
 * Run: node .tools/browser-click.mjs            write the page, print its path
 *      node .tools/browser-click.mjs --run      run it headless and print the log
 */
